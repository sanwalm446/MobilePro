// Simple yet secure SHA-256 password hashing utility for client-side storage
export async function hashPassword(plainText: string): Promise<string> {
  if (!plainText) return '';
  try {
    if (typeof window !== 'undefined' && window.crypto && window.crypto.subtle) {
      const msgUint8 = new TextEncoder().encode(plainText + '_pakmobile_salt_2026');
      const hashBuffer = await window.crypto.subtle.digest('SHA-256', msgUint8);
      const hashArray = Array.from(new Uint8Array(hashBuffer));
      return hashArray.map((b) => b.toString(16).padStart(2, '0')).join('');
    }
  } catch (err) {
    console.error('Crypto subtle failed, using standard fallback', err);
  }
  // Safe deterministic fallback hash
  let hash = 0;
  const str = plainText + '_pakmobile_salt_2026';
  for (let i = 0; i < str.length; i++) {
    const char = str.charCodeAt(i);
    hash = (hash << 5) - hash + char;
    hash |= 0;
  }
  return 'hashed_' + Math.abs(hash).toString(16).padStart(12, '0');
}

